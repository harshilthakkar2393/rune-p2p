import * as z from "zod";

/**
 * Logical schema for the rune index document.
 *
 * The index is a flat map of nodes (folders + pages); the tree is derived at
 * render time by grouping on parentId/folderId. Page BODIES are not here —
 * each page's content lives in its own Y.Doc (IndexedDB db "rune:page:<id>").
 *
 * Invariants zod cannot express (enforced where mutations happen):
 * - a folder's parentId chain must never cycle (check on move)
 * - a parentId/folderId pointing at a missing folder renders at root, never throws
 */

const EntityId = z.nanoid();
const Timestamp = z.int().positive();
// Fractional index (e.g. "a0", "a0V") — insert-between without renumbering,
// merge-safe under concurrent edits. Generated by the `fractional-indexing` lib.
const SortKey = z.string().min(1);

const folder = z.object({
  id: EntityId,
  type: z.literal("folder"),
  name: z.string().min(1).max(200),
  parentId: EntityId.nullable(),
  sortKey: SortKey,
  createdAt: Timestamp,
  updatedAt: Timestamp,
});

const page = z.object({
  id: EntityId,
  type: z.literal("page"),
  title: z.string().max(300),
  folderId: EntityId.nullable(),
  sortKey: SortKey,
  createdAt: Timestamp,
  updatedAt: Timestamp,
});

const node = z.discriminatedUnion("type", [folder, page]);
const index = z.record(EntityId, node);

export type Folder = z.infer<typeof folder>;
export type Page = z.infer<typeof page>;
export type Node = z.infer<typeof node>;
export type Index = z.infer<typeof index>;

// Precompiled (zod 4.5 z.compile): identical behavior, ~3-9x faster parse.
// Falls back to normal parsing gracefully where codegen is unavailable.
export const FolderSchema = z.compile(folder);
export const PageSchema = z.compile(page);
export const NodeSchema = z.compile(node);
export const IndexSchema = z.compile(index);
